#!/usr/bin/env python3
"""
Video Question Answering Evaluation Script

This script evaluates the results generated by infer.py, providing comprehensive
analysis and additional metrics beyond what was computed during inference.

Usage:
    python eval.py --input_dir /path/to/inference_output --output_dir /path/to/eval_output
    python eval.py --input_dir /path/to/inference_output --compare /path/to/another_output
    python eval.py --input_dir /path/to/inference_output --recompute_metrics
"""

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path

# Import from libs modules
from libs.evaluation_metrics import EvaluationMetrics
from libs.inference_results_loader import InferenceResultsLoader
from libs.evaluation_analyzer import EvaluationAnalyzer
from libs.results_comparator import ResultsComparator
from libs.evaluation_reporter import EvaluationReporter
from libs.custom_logger import create_logger


def setup_logging(name="VQA", log_dir=None, console_level="INFO", file_level="DEBUG"):
    """Setup logging without model dependencies."""
    if log_dir is None:
        from pathlib import Path

        current_dir = Path.cwd()
        log_dir = current_dir / "logs"

    return create_logger(
        name=name, log_dir=log_dir, console_level=console_level, file_level=file_level
    )


def apply_answer_transformations(results, add_dot, convert_digit_to_alpha):
    """
    Apply testing transformations to answer outputs.

    Args:
        results: List of inference results
        add_dot: Whether to add dot to end of answers
        convert_digit_to_alpha: Whether to convert single digits to alpha

    Returns:
        Modified results with transformed answers
    """
    digit_to_alpha = {
        "1": "one",
        "2": "two",
        "3": "three",
        "4": "four",
        "5": "five",
        "6": "six",
        "7": "seven",
        "8": "eight",
        "9": "nine",
    }

    transformed_count = 0
    dot_added_count = 0
    digit_converted_count = 0

    # For debugging - show first few transformations
    debug_examples = []

    for i, result in enumerate(results):
        if "output" in result and "predicted_answer" in result["output"]:
            original_answer = result["output"]["predicted_answer"]
            answer = original_answer

            if convert_digit_to_alpha and answer.strip() in digit_to_alpha:
                answer = digit_to_alpha[answer.strip()]
                digit_converted_count += 1

            if add_dot and answer and not answer.endswith("."):
                answer = answer + "."
                dot_added_count += 1

            if answer != original_answer:
                result["output"]["predicted_answer"] = answer
                transformed_count += 1

                # Store examples for debugging
                if len(debug_examples) < 3:
                    debug_examples.append(
                        {"index": i, "original": original_answer, "transformed": answer}
                    )

    print("Transformation summary:")
    print(f"  Total results processed: {len(results)}")
    print(f"  Results with transformed answers: {transformed_count}")
    if add_dot:
        print(f"  Dots added to answers: {dot_added_count}")
    if convert_digit_to_alpha:
        print(f"  Digits converted to alpha: {digit_converted_count}")

    # Show examples of transformations
    if debug_examples:
        print("  Example transformations:")
        for example in debug_examples:
            print(
                f"    [{example['index']}] '{example['original']}' -> '{example['transformed']}'"
            )

    return results


def update_original_experiment_statistics(input_dir, results, logger):
    """
    Update the original experiment_statistics.json file with recomputed metrics.

    Args:
        input_dir: Path to the original experiment directory
        results: List of updated results with new metrics
        logger: Logger instance
    """
    try:
        input_path = Path(input_dir)
        stats_file = input_path / "summary" / "experiment_statistics.json"

        if not stats_file.exists():
            logger.warning(
                f"Original experiment_statistics.json not found at {stats_file}"
            )
            return False

        # Load original statistics
        with open(stats_file, "r", encoding="utf-8") as f:
            original_stats = json.load(f)

        logger.info(f"Updating original experiment statistics file: {stats_file}")

        # Update individual result files with new metrics
        individual_dir = input_path / "individual_results"
        if individual_dir.exists():
            logger.info("Updating individual result files with recomputed metrics...")

            for result in results:
                if "file_stem" in result:
                    file_path = individual_dir / f"{result['file_stem']}.json"
                    if file_path.exists():
                        try:
                            # Load original individual file
                            with open(file_path, "r", encoding="utf-8") as f:
                                original_individual = json.load(f)

                            # Update only the metrics and predicted answer
                            if "evaluation_metrics" in result:
                                original_individual["evaluation_metrics"] = result[
                                    "evaluation_metrics"
                                ]

                            if (
                                "output" in result
                                and "predicted_answer" in result["output"]
                            ):
                                if "output" not in original_individual:
                                    original_individual["output"] = {}
                                original_individual["output"]["predicted_answer"] = (
                                    result["output"]["predicted_answer"]
                                )

                            # Save updated individual file
                            with open(file_path, "w", encoding="utf-8") as f:
                                json.dump(
                                    original_individual, f, indent=2, ensure_ascii=False
                                )

                        except (IOError, json.JSONDecodeError) as e:
                            logger.warning(
                                f"Failed to update individual file {file_path}: {e}"
                            )

        # Update detailed_results.json file if it exists
        detailed_results_file = input_path / "summary" / "detailed_results.json"
        if detailed_results_file.exists():
            logger.info("Updating detailed_results.json with recomputed metrics...")
            try:
                # Load the detailed results file
                with open(detailed_results_file, "r", encoding="utf-8") as f:
                    detailed_results = json.load(f)

                # Create a mapping from file_stem to updated metrics
                results_by_file_stem = {}
                for result in results:
                    if "file_stem" in result.get("evaluation_metrics", {}):
                        file_stem = result["evaluation_metrics"]["file_stem"]
                        results_by_file_stem[file_stem] = result

                # Update detailed results with new metrics and predicted answers
                updated_count = 0
                for detailed_result in detailed_results:
                    if "file_stem" in detailed_result and detailed_result["file_stem"] in results_by_file_stem:
                        updated_result = results_by_file_stem[detailed_result["file_stem"]]
                        
                        # Update metrics section with all new metrics
                        if "evaluation_metrics" in updated_result:
                            # Create metrics dict excluding file_stem
                            new_metrics = {k: v for k, v in updated_result["evaluation_metrics"].items() if k != "file_stem"}
                            detailed_result["metrics"] = new_metrics
                            
                        # Update predicted answer if available
                        if "output" in updated_result and "predicted_answer" in updated_result["output"]:
                            detailed_result["predicted_answer"] = updated_result["output"]["predicted_answer"]
                            
                        updated_count += 1

                # Save updated detailed results
                with open(detailed_results_file, "w", encoding="utf-8") as f:
                    json.dump(detailed_results, f, indent=2, ensure_ascii=False)

                logger.info(f"Updated {updated_count} entries in detailed_results.json")

            except (IOError, json.JSONDecodeError) as e:
                logger.warning(f"Failed to update detailed_results.json: {e}")

        # Recompute performance metrics from updated results
        metrics_data = []
        for result in results:
            if "evaluation_metrics" in result:
                metrics_data.append(result["evaluation_metrics"])

        if metrics_data:
            import pandas as pd

            metrics_df = pd.DataFrame(metrics_data)

            # Update performance metrics in the original structure
            original_stats["performance_metrics"] = {
                "sts_score": {
                    "mean": float(metrics_df["sts_score"].mean()),
                    "std": float(metrics_df["sts_score"].std()),
                    "min": float(metrics_df["sts_score"].min()),
                    "max": float(metrics_df["sts_score"].max()),
                    "median": float(metrics_df["sts_score"].median()),
                    "q25": float(metrics_df["sts_score"].quantile(0.25)),
                    "q75": float(metrics_df["sts_score"].quantile(0.75)),
                },
                "meteor_score": {
                    "mean": float(metrics_df["meteor_score"].mean()),
                    "std": float(metrics_df["meteor_score"].std()),
                    "min": float(metrics_df["meteor_score"].min()),
                    "max": float(metrics_df["meteor_score"].max()),
                    "median": float(metrics_df["meteor_score"].median()),
                    "q25": float(metrics_df["meteor_score"].quantile(0.25)),
                    "q75": float(metrics_df["meteor_score"].quantile(0.75)),
                },
                "bert_f1": {
                    "mean": float(metrics_df["bert_f1"].mean()),
                    "std": float(metrics_df["bert_f1"].std()),
                    "min": float(metrics_df["bert_f1"].min()),
                    "max": float(metrics_df["bert_f1"].max()),
                    "median": float(metrics_df["bert_f1"].median()),
                    "q25": float(metrics_df["bert_f1"].quantile(0.25)),
                    "q75": float(metrics_df["bert_f1"].quantile(0.75)),
                },
                "ndcg_score": {
                    "mean": float(metrics_df["ndcg_score"].mean()),
                    "std": float(metrics_df["ndcg_score"].std()),
                    "min": float(metrics_df["ndcg_score"].min()),
                    "max": float(metrics_df["ndcg_score"].max()),
                },
            }

        # Add update metadata to track changes
        if "update_history" not in original_stats:
            original_stats["update_history"] = []

        update_record = {
            "timestamp": datetime.now().isoformat(),
            "updated_by": "eval.py",
            "changes_made": "Recomputed metrics with transformations",
            "samples_updated": len(results),
        }
        original_stats["update_history"].append(update_record)

        # Save updated statistics
        with open(stats_file, "w", encoding="utf-8") as f:
            json.dump(original_stats, f, indent=2, ensure_ascii=False)

        logger.info(
            f"Successfully updated original experiment statistics: {stats_file}"
        )
        logger.info(f"Updated {len(results)} samples with new metrics")

        return True

    except (IOError, json.JSONDecodeError, KeyError) as e:
        logger.error(f"Error updating original experiment statistics: {str(e)}")
        import traceback

        traceback.print_exc()
        return False


def main():
    parser = argparse.ArgumentParser(
        description="Comprehensive evaluation of Video Question Answering inference results"
    )

    # Required arguments
    parser.add_argument(
        "--input_dir",
        "-i",
        type=str,
        required=True,
        help="Path to inference output directory from infer.py",
    )

    # Output options
    parser.add_argument(
        "--output_dir",
        "-o",
        type=str,
        help="Output directory for evaluation results (default: eval_output_TIMESTAMP)",
    )

    # Analysis options
    parser.add_argument(
        "--recompute_metrics",
        action="store_true",
        help="Recompute all evaluation metrics with current setup",
    )

    parser.add_argument(
        "--compare",
        type=str,
        help="Path to another inference output directory for comparison",
    )

    # Filtering options
    parser.add_argument(
        "--filter_successful_only",
        action="store_true",
        help="Only analyze samples with successful inferences",
    )

    parser.add_argument(
        "--sample_limit",
        type=int,
        help="Limit analysis to first N samples (for testing)",
    )

    # Testing options
    parser.add_argument(
        "--add_dot_to_answer",
        action="store_true",
        help="Add dot '.' to the end of answer output for testing",
    )

    parser.add_argument(
        "--convert_digit_to_alpha",
        action="store_true",
        help="Convert single digits (1-9) to alpha (one, two, ..., nine) for testing",
    )

    # Update options
    parser.add_argument(
        "--update_original",
        action="store_true",
        help="Update the original experiment_statistics.json and individual result files with recomputed metrics",
    )

    args = parser.parse_args()

    # Set up logging
    logger = setup_logging()

    # Validate input directory
    input_dir = Path(args.input_dir)
    if not input_dir.exists():
        logger.error(f"Input directory not found: {input_dir}")
        sys.exit(1)

    # Set up output directory
    if args.output_dir:
        output_dir = Path(args.output_dir)
    else:
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        output_dir = Path(f"eval_output_{timestamp}")

    try:
        # Load inference results
        logger.info(f"Loading results from: {input_dir}")
        loader = InferenceResultsLoader(input_dir)
        results = loader.load_individual_results()

        logger.info(f"Loaded {len(results)} individual results")

        if not results:
            logger.error("No results found in input directory")
            sys.exit(1)

        # Apply filtering
        if args.filter_successful_only:
            original_count = len(results)
            results = [
                r for r in results if r.get("output", {}).get("predicted_answer")
            ]
            logger.info(
                f"Filtered to {len(results)} successful inferences (from {original_count})"
            )

        if args.sample_limit and len(results) > args.sample_limit:
            logger.info(f"Limiting analysis to first {args.sample_limit} samples")
            results = results[: args.sample_limit]

        # Apply testing transformations to answers if requested
        if args.add_dot_to_answer or args.convert_digit_to_alpha:
            logger.info("Applying testing transformations to answers...")
            results = apply_answer_transformations(
                results, args.add_dot_to_answer, args.convert_digit_to_alpha
            )

        # Initialize evaluator and analyzer
        logger.info("Initializing evaluation metrics...")
        evaluator = EvaluationMetrics()
        analyzer = EvaluationAnalyzer(evaluator)

        # If recompute_metrics is requested, explicitly recompute metrics for each result
        if args.recompute_metrics:
            logger.info("Recomputing evaluation metrics for all results...")
            for i, result in enumerate(results):
                has_output = "output" in result and "predicted_answer" in result["output"]
                has_ground_truth = "ground_truth" in result and "correct_answer" in result["ground_truth"]
                
                if has_output and has_ground_truth:
                    predicted_answer = result["output"]["predicted_answer"]
                    correct_answer = result["ground_truth"]["correct_answer"]
                    
                    # Get incorrect answers if available
                    incorrect_answers = result["ground_truth"].get("incorrect_answers", [])

                    # Recompute all metrics
                    try:
                        new_metrics = evaluator.compute_all_metrics(
                            predicted_answer, correct_answer, incorrect_answers
                        )
                        # Add file_stem for tracking
                        if "metadata" in result and "file_stem" in result["metadata"]:
                            new_metrics["file_stem"] = result["metadata"]["file_stem"]
                        elif "file_stem" in result.get("evaluation_metrics", {}):
                            new_metrics["file_stem"] = result["evaluation_metrics"]["file_stem"]

                        # Update the result with new metrics
                        result["evaluation_metrics"] = new_metrics
                        
                        if (i + 1) % 100 == 0:  # Log progress every 100 samples
                            logger.info(f"Recomputed metrics for {i + 1}/{len(results)} samples")
                            
                    except Exception as e:
                        logger.warning(f"Failed to recompute metrics for result {i}: {e}")

            logger.info(f"Completed recomputing metrics for {len(results)} results")

        # Perform comprehensive analysis
        logger.info("Performing comprehensive analysis...")
        analysis = analyzer.analyze_results(
            results, recompute_metrics=False  # Already recomputed above if needed
        )

        # Comparison analysis if requested
        if args.compare:
            logger.info(f"Loading comparison results from: {args.compare}")
            compare_loader = InferenceResultsLoader(Path(args.compare))
            compare_results = compare_loader.load_individual_results()

            if compare_results:
                logger.info("Performing comparison analysis...")
                comparator = ResultsComparator()
                comparison = comparator.compare_experiments(
                    results,
                    compare_results,
                    f"Main ({input_dir.name})",
                    f"Compare ({Path(args.compare).name})",
                )
                analysis["comparison"] = comparison
            else:
                logger.warning("No results found in comparison directory")

        # Generate comprehensive report
        if not args.update_original:
            logger.info(f"Generating evaluation report in: {output_dir}")
            reporter = EvaluationReporter(output_dir)
            reporter.generate_report(analysis, input_dir, results)
        else:
            logger.info(
                "Skipping eval report generation as --update_original was specified"
            )

        # Update original experiment statistics if requested
        if args.update_original:
            logger.info("Updating original experiment statistics...")
            success = update_original_experiment_statistics(input_dir, results, logger)
            if success:
                logger.info("Original experiment files updated successfully!")
            else:
                logger.error("Failed to update original experiment files")

        # Print summary
        logger.info("Evaluation completed successfully!")

        if "basic_statistics" in analysis:
            stats = analysis["basic_statistics"]
            logger.info(stats)
            logger.info("------")

            logger.info("Summary:")
            logger.info(f"  Total samples: {stats.get('total_samples', 0)}")
            logger.info(f"  Success rate: {stats.get('success_rate', 0):.2%}")

            if stats.get("metrics_available") and "metric_statistics" in stats:
                logger.info("  Key metrics (mean ± std):")
                for metric in ["sts_score", "meteor_score", "bert_f1", "ndcg_score"]:
                    if metric in stats["metric_statistics"]:
                        m_stats = stats["metric_statistics"][metric]
                        logger.info(
                            f"    {metric}: {m_stats['mean']:.4f} ± {m_stats['std']:.4f}"
                        )

        if args.compare and "comparison" in analysis:
            logger.info("Comparison summary:")
            comp_stats = analysis["comparison"]["metric_comparisons"]
            for metric in ["sts_score", "meteor_score", "bert_f1", "ndcg_score"]:
                if metric in comp_stats:
                    change = comp_stats[metric]["percent_change"]
                    logger.info(f"    {metric}: {change:+.2f}% change")

        if not args.update_original:
            logger.info(f"Detailed results available in: {output_dir}")
        else:
            logger.info(f"Original experiment files updated in: {input_dir}")

    except (IOError, json.JSONDecodeError, KeyError, ValueError) as e:
        logger.error(f"Error during evaluation: {str(e)}")
        import traceback

        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()
